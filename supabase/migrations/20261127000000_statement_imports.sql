-- Conferir com o banco (27/11/2026): a fatura do cartão (PDF) e o extrato da conta (CSV) do Santander.
--
-- Guarda o que foi lido do arquivo (não o arquivo): as linhas da fatura ou do extrato, para conferir de novo
-- depois de corrigir, sem precisar enviar outra vez. A comparação com os lançamentos é feita na hora
-- (lib/statements/compare.ts); aqui fica só a lista do banco e o que a pessoa mandou ignorar.

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'payment_methods_id_user_id_key') then
    alter table public.payment_methods add constraint payment_methods_id_user_id_key unique (id, user_id);
  end if;
end;
$$;

create table if not exists public.statement_imports (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kind text not null check (kind in ('fatura', 'extrato')),
  bank text not null default 'santander',
  payment_method_id bigint not null,
  month text check (month is null or month ~ '^\d{4}-\d{2}$'),            -- fatura: mês do Atlas (fechamento)
  period_from text not null check (period_from ~ '^\d{4}-\d{2}-\d{2}$'),
  period_to text not null check (period_to ~ '^\d{4}-\d{2}-\d{2}$'),
  file_name text,
  data jsonb not null,                                                     -- Fatura ou Extrato lido (lib/statements/santander.ts)
  ignored text[] not null default '{}',                                    -- chaves dos problemas ignorados
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Enviar a mesma fatura de novo substitui a anterior (o extrato pode ter vários períodos)
  unique (user_id, kind, payment_method_id, month),
  foreign key (payment_method_id, user_id) references public.payment_methods (id, user_id) on delete cascade
);
create index if not exists statement_imports_user_idx on public.statement_imports (user_id, kind, created_at desc);

alter table public.statement_imports enable row level security;
drop policy if exists "dono" on public.statement_imports;
create policy "dono" on public.statement_imports for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on table public.statement_imports to authenticated;
revoke all on table public.statement_imports from anon;
