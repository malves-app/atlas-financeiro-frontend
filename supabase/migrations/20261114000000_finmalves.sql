-- ---------- funções usadas pelo site (rodam com as permissões de quem chama) ----------

-- Nomes já usados no dia a dia, com a categoria e a forma de pagamento mais recentes de cada um
create or replace function public.fm_suggestions()
returns table (name text, category_id bigint, payment text, uses integer)
language sql
stable
security invoker
set search_path = ''
as $$
  with ranked as (
    select e.name, e.category_id, e.payment,
           count(*) over (partition by lower(trim(e.name))) as uses,
           row_number() over (
             partition by lower(trim(e.name))
             order by (e.category_id is null), e.month desc, e.id desc
           ) as rn
      from public.entries e
     where e.kind = 'avulso'
  )
  select trim(r.name), r.category_id, r.payment, r.uses::integer
    from ranked r
   where r.rn = 1
   order by r.uses desc, trim(r.name)
   limit 400;
$$;

-- Quantas vezes cada categoria foi usada desde um mês (para ordenar o lançamento rápido)
create or replace function public.fm_category_usage(p_from text)
returns table (category_id bigint, uses integer)
language sql
stable
security invoker
set search_path = ''
as $$
  select e.category_id, count(*)::integer
    from public.entries e
   where e.kind = 'avulso' and e.month >= p_from and e.category_id is not null
   group by e.category_id;
$$;

-- Preenche categorias vazias de um mês usando o histórico (mesmo nome = mesma categoria)
create or replace function public.fm_fill_categories(p_month text)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  n integer;
begin
  update public.entries e
     set category_id = h.category_id
    from (
      select distinct on (lower(trim(e2.name))) lower(trim(e2.name)) as key, e2.category_id
        from public.entries e2
       where e2.category_id is not null
       order by lower(trim(e2.name)), e2.month desc, e2.id desc
    ) h
   where e.month = p_month
     and e.category_id is null
     and lower(trim(e.name)) = h.key;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- Apaga os lançamentos, entradas e fixos de quem chama (usado antes de importar a planilha)
create or replace function public.fm_reset_data()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  delete from public.entries where user_id = (select auth.uid());
  delete from public.incomes where user_id = (select auth.uid());
  delete from public.recurring where user_id = (select auth.uid());
  delete from public.generated_months where user_id = (select auth.uid());
end;
$$;

revoke execute on function public.fm_suggestions() from public, anon;
revoke execute on function public.fm_category_usage(text) from public, anon;
revoke execute on function public.fm_fill_categories(text) from public, anon;
revoke execute on function public.fm_reset_data() from public, anon;
grant execute on function public.fm_suggestions() to authenticated;
grant execute on function public.fm_category_usage(text) to authenticated;
grant execute on function public.fm_fill_categories(text) to authenticated;
grant execute on function public.fm_reset_data() to authenticated;
