-- AtlasFinanceiro: estrutura do banco no Supabase.
-- Rode uma vez no SQL Editor do Supabase (ou com `supabase db push`).
-- Valores em centavos (inteiros) e datas como texto YYYY-MM-DD para evitar problemas de fuso.
-- Cada linha pertence a um usuário (user_id) e a segurança por linha (RLS) garante que
-- cada pessoa só vê e altera os próprios dados.

-- ---------- tabelas ----------

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  emoji text not null default '🏷️',
  budget_cents integer,
  sort integer not null default 0,
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

-- Modelos de fixos: contas do mês (conta corrente) e do cartão (assinaturas e parcelas)
create table if not exists public.recurring (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kind text not null check (kind in ('fixo', 'cartao')),
  name text not null,
  amount_cents integer not null,
  day integer check (day between 1 and 31),
  payment text not null check (payment in ('conta', 'credito')),
  category_id bigint references public.categories (id) on delete set null,
  installments integer,          -- null = todo mês; senão, número total de parcelas
  start_month text not null,     -- YYYY-MM do primeiro mês (parcela 1)
  end_month text,                -- último mês em que aparece (null = sem fim)
  created_at timestamptz not null default now()
);

-- Tudo o que sai: fixos do mês, fixos do cartão e gastos do dia a dia
create table if not exists public.entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  month text not null,           -- mês de referência (aba da planilha / fatura)
  kind text not null check (kind in ('fixo', 'cartao', 'avulso')),
  name text not null,
  amount_cents integer not null,
  date text,                     -- data da compra ou vencimento (YYYY-MM-DD)
  payment text not null check (payment in ('conta', 'credito')),
  category_id bigint references public.categories (id) on delete set null,
  paid boolean,
  installment_no integer,
  installment_total integer,
  recurring_id bigint references public.recurring (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.incomes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  month text not null,
  name text not null,
  amount_cents integer not null,
  date text,
  created_at timestamptz not null default now()
);

-- Meses em que os fixos já foram criados (para não recriar o que você apagou)
create table if not exists public.generated_months (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  month text not null,
  primary key (user_id, month)
);

create table if not exists public.settings (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  key text not null,
  value text not null,
  primary key (user_id, key)
);

create index if not exists categories_user_idx on public.categories (user_id);
create index if not exists recurring_user_idx on public.recurring (user_id);
create index if not exists recurring_category_idx on public.recurring (category_id);
create index if not exists entries_user_month_idx on public.entries (user_id, month);
create index if not exists entries_category_idx on public.entries (category_id);
create index if not exists entries_recurring_idx on public.entries (recurring_id);
create index if not exists entries_name_idx on public.entries (user_id, lower(trim(name)));
create index if not exists incomes_user_month_idx on public.incomes (user_id, month);

-- ---------- segurança por linha ----------

alter table public.categories enable row level security;
alter table public.recurring enable row level security;
alter table public.entries enable row level security;
alter table public.incomes enable row level security;
alter table public.generated_months enable row level security;
alter table public.settings enable row level security;

drop policy if exists "dono" on public.categories;
create policy "dono" on public.categories for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

drop policy if exists "dono" on public.recurring;
