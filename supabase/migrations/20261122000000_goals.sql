-- Metas: limites de gasto (do mês ou do ano) e metas de guardar dinheiro.
--   kind: 'total' (todos os gastos), 'dia_a_dia' (só os avulsos), 'cartao' (a fatura do mês),
--         'categoria' (uma categoria) e 'guardar' (entradas − gastos, quanto sobra).
--   period: 'mes' (vale todo mês, de start_month até end_month) ou 'ano' (start_month = AAAA-01, end_month = AAAA-12).
-- Mudar o valor de uma meta do mês a partir de um mês encerra a versão antiga no mês anterior e cria outra,
-- então os meses que já passaram continuam avaliados com o valor da época.

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kind text not null check (kind in ('total', 'dia_a_dia', 'cartao', 'categoria', 'guardar')),
  period text not null default 'mes' check (period in ('mes', 'ano')),
  category_id bigint references public.categories (id) on delete cascade,
  target_cents integer not null check (target_cents > 0),
  start_month text not null,     -- YYYY-MM do primeiro mês em que vale
  end_month text,                -- último mês em que vale (null = sem fim)
  created_at timestamptz not null default now(),
  check ((kind = 'categoria') = (category_id is not null)),
  check (period = 'mes' or end_month is not null)
);
create index if not exists goals_user_idx on public.goals (user_id);
create index if not exists goals_category_idx on public.goals (category_id);

alter table public.goals enable row level security;
drop policy if exists "dono" on public.goals;
create policy "dono" on public.goals for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on table public.goals to authenticated;
revoke all on table public.goals from anon;

-- O "valor previsto por mês" das categorias (Ajustes) vira meta mensal da categoria,
-- valendo desde o primeiro mês com lançamentos (antes ele aparecia em todos os meses).
insert into public.goals (user_id, kind, period, category_id, target_cents, start_month)
select c.user_id, 'categoria', 'mes', c.id, c.budget_cents,
       coalesce(
         (select min(e.month) from public.entries e where e.user_id = c.user_id),
         to_char(now() at time zone 'America/Fortaleza', 'YYYY-MM')
       )
  from public.categories c
 where c.budget_cents is not null and c.budget_cents > 0 and not c.archived
   and not exists (
     select 1 from public.goals g where g.user_id = c.user_id and g.kind = 'categoria' and g.category_id = c.id
   );
update public.categories set budget_cents = null where budget_cents is not null;

-- Totais por mês para as metas: gastos por tipo, categoria e cartão (on_card) e as entradas (kind = 'entrada').
-- "No cartão" segue a forma de pagamento; sem forma conhecida, vale o tipo do lançamento (como em lib/data.ts).
create or replace function public.fm_month_totals(p_from text, p_to text)
returns table (month text, kind text, category_id bigint, on_card boolean, total bigint)
language sql
stable
security invoker
set search_path = ''
as $$
  select e.month, e.kind, e.category_id, coalesce(pm.is_credit, e.kind = 'cartao'), sum(e.amount_cents)::bigint
    from public.entries e
    left join public.payment_methods pm on pm.id = e.payment_method_id
   where e.month between p_from and p_to
   group by 1, 2, 3, 4
  union all
  select i.month, 'entrada', null, false, sum(i.amount_cents)::bigint
    from public.incomes i
   where i.month between p_from and p_to
   group by 1;
$$;
revoke execute on function public.fm_month_totals(text, text) from public, anon;
grant execute on function public.fm_month_totals(text, text) to authenticated;
