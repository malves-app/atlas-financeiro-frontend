-- Conferir com o banco (27/11/2026): lembrar como cada linha do banco foi lançada.
--
-- A chave é o texto do banco sem números ("cartao:uber uber trip help", "conta:hypertech software").
-- Vem de duas fontes: o que a pessoa aprovou na conferência e as linhas que bateram com um lançamento do Atlas.
-- Na próxima fatura ou extrato, a mesma linha já vem com o nome e a categoria de antes (lib/statements/suggest.ts).

create table if not exists public.statement_rules (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  key text not null check (length(key) between 3 and 120),
  name text not null check (length(btrim(name)) between 1 and 80),
  category_id bigint,
  subcategory_id bigint,
  updated_at timestamptz not null default now(),
  unique (user_id, key),
  -- Apagar a categoria (ou a subcategoria) só limpa a categoria da regra; o nome continua valendo
  foreign key (category_id, user_id) references public.categories (id, user_id) on delete set null (category_id),
  foreign key (subcategory_id, category_id) references public.subcategories (id, category_id) on delete set null (subcategory_id)
);

alter table public.statement_rules enable row level security;
drop policy if exists "dono" on public.statement_rules;
create policy "dono" on public.statement_rules for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on table public.statement_rules to authenticated;
revoke all on table public.statement_rules from anon;
