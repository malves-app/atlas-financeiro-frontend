-- Formas de pagamento configuráveis (o "Tipo" da planilha: Conta Corrente, Crédito, Pix, outro cartão...).
-- Cada cartão de crédito tem o próprio dia de fechamento.
-- Os lançamentos que já existem são convertidos: 'conta' -> "Conta Corrente", 'credito' -> "Crédito".

create table if not exists public.payment_methods (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  is_credit boolean not null default false,  -- cartão de crédito: usa o dia de fechamento
  closing_day integer check (closing_day between 1 and 31),
  color text not null default '#2a78d6',
  sort integer not null default 0,
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);
create index if not exists payment_methods_user_idx on public.payment_methods (user_id);

alter table public.payment_methods enable row level security;
drop policy if exists "dono" on public.payment_methods;
create policy "dono" on public.payment_methods for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on table public.payment_methods to authenticated;
revoke all on table public.payment_methods from anon;

alter table public.entries add column if not exists payment_method_id bigint references public.payment_methods (id) on delete set null;
alter table public.recurring add column if not exists payment_method_id bigint references public.payment_methods (id) on delete set null;
create index if not exists entries_payment_method_idx on public.entries (payment_method_id);
create index if not exists recurring_payment_method_idx on public.recurring (payment_method_id);

-- Converte os dados existentes (só roda enquanto a coluna antiga "payment" existir)
do $$
begin
  if exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'entries' and column_name = 'payment'
  ) then
    insert into public.payment_methods (user_id, name, is_credit, closing_day, color, sort)
    select u.user_id, v.name, v.is_credit, v.closing_day, v.color, v.sort
      from (
        select user_id from public.entries
        union select user_id from public.recurring
        union select user_id from public.categories
      ) u
     cross join (values
       ('Conta Corrente', false, null::integer, '#2a78d6', 1),
       ('Crédito', true, 25, '#eb6834', 2)
     ) as v (name, is_credit, closing_day, color, sort)
    on conflict (user_id, name) do nothing;

    -- dia de fechamento que estava nos ajustes
    update public.payment_methods pm
       set closing_day = nullif(s.value, '')::integer
      from public.settings s
     where s.user_id = pm.user_id and s.key = 'closing_day' and pm.is_credit
       and s.value ~ '^[0-9]+$' and s.value::integer between 1 and 31;

    execute $q$
      update public.entries e
         set payment_method_id = pm.id
        from public.payment_methods pm
       where pm.user_id = e.user_id
         and pm.name = case e.payment when 'credito' then 'Crédito' else 'Conta Corrente' end
         and e.payment_method_id is null
    $q$;
    execute $q$
      update public.recurring r
         set payment_method_id = pm.id
        from public.payment_methods pm
       where pm.user_id = r.user_id
         and pm.name = case r.payment when 'credito' then 'Crédito' else 'Conta Corrente' end
         and r.payment_method_id is null
    $q$;

    alter table public.entries drop column payment;
    alter table public.recurring drop column payment;
  end if;
end;
$$;

delete from public.settings where key = 'closing_day';

-- Sugestões agora devolvem a forma de pagamento (id) usada da última vez
drop function if exists public.fm_suggestions();
create function public.fm_suggestions()
returns table (name text, category_id bigint, payment_method_id bigint, uses integer)
language sql
stable
security invoker
set search_path = ''
as $$
  with ranked as (
    select e.name, e.category_id, e.payment_method_id,
           count(*) over (partition by lower(trim(e.name))) as uses,
           row_number() over (
             partition by lower(trim(e.name))
             order by (e.category_id is null), e.month desc, e.id desc
           ) as rn
      from public.entries e
     where e.kind = 'avulso'
  )
  select trim(r.name), r.category_id, r.payment_method_id, r.uses::integer
    from ranked r
   where r.rn = 1
   order by r.uses desc, trim(r.name)
   limit 400;
$$;
revoke execute on function public.fm_suggestions() from public, anon;
grant execute on function public.fm_suggestions() to authenticated;
