-- Investimentos: onde está o dinheiro guardado (caixinha, renda fixa, Tesouro, ações, cripto...) e as
-- movimentações de cada um. Funciona à parte do resto do site: não entra no saldo do mês, nas metas
-- nem nas estatísticas.
--   investments.kind: tipo, só para agrupar e colorir.
--   investments.target_cents: quanto quer juntar ali (opcional).
--   investment_moves.kind: 'aporte' (colocou dinheiro), 'resgate' (tirou) ou 'saldo' (conferiu quanto tem;
--   amount_cents é o saldo novo e a diferença para o saldo anterior é o rendimento do período).

create table if not exists public.investments (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 80),
  kind text not null default 'outro'
    check (kind in ('caixinha', 'renda_fixa', 'tesouro', 'acoes', 'fundos', 'cripto', 'previdencia', 'outro')),
  institution text check (institution is null or length(institution) <= 60),
  target_cents bigint check (target_cents is null or target_cents > 0),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, user_id)
);
create index if not exists investments_user_idx on public.investments (user_id);

-- A movimentação aponta para (investimento, dono): não dá para lançar num investimento de outra pessoa.
create table if not exists public.investment_moves (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  investment_id bigint not null,
  kind text not null check (kind in ('aporte', 'resgate', 'saldo')),
  amount_cents bigint not null check (amount_cents >= 0 and (kind = 'saldo' or amount_cents > 0)),
  date text not null check (date ~ '^\d{4}-\d{2}-\d{2}$'),  -- YYYY-MM-DD
  note text check (note is null or length(note) <= 140),
  created_at timestamptz not null default now(),
  foreign key (investment_id, user_id) references public.investments (id, user_id) on delete cascade
);
create index if not exists investment_moves_investment_idx on public.investment_moves (investment_id, date);
create index if not exists investment_moves_user_idx on public.investment_moves (user_id);

alter table public.investments enable row level security;
drop policy if exists "dono" on public.investments;
create policy "dono" on public.investments for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

alter table public.investment_moves enable row level security;
drop policy if exists "dono" on public.investment_moves;
create policy "dono" on public.investment_moves for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

grant select, insert, update, delete on table public.investments, public.investment_moves to authenticated;
revoke all on table public.investments, public.investment_moves from anon;
