-- Configurações (26/11/2026): subcategorias e ícone/banco das formas de pagamento.
--
-- Subcategorias ficam dentro de uma categoria (Alimentação → Supermercado, Restaurante, Delivery...).
-- O lançamento continua apontando para a categoria (metas, painel e estatísticas somam por ela) e ganha,
-- opcionalmente, a subcategoria. A subcategoria precisa ser da mesma categoria do lançamento.
--
-- Formas de pagamento ganham:
--   icon: o tipo (conta, pix, dinheiro, credito, debito, vale, carteira, boleto, poupanca, outro), só para o desenho.
--         Quem decide se tem fatura continua sendo is_credit (o site grava icon = 'credito' junto com is_credit).
--   bank: banco/instituição (nubank, itau, ...), opcional, para o selo com a cor do banco.

-- ---------- subcategorias ----------

-- (id, user_id) único em categories: a subcategoria aponta para a categoria do próprio dono
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'categories_id_user_id_key') then
    alter table public.categories add constraint categories_id_user_id_key unique (id, user_id);
  end if;
end;
$$;

create table if not exists public.subcategories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  category_id bigint not null,
  name text not null check (length(btrim(name)) between 1 and 40),
  sort integer not null default 0,
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique (category_id, name),
  unique (id, category_id),
  foreign key (category_id, user_id) references public.categories (id, user_id) on delete cascade
);
create index if not exists subcategories_user_idx on public.subcategories (user_id);

alter table public.subcategories enable row level security;
drop policy if exists "dono" on public.subcategories;
create policy "dono" on public.subcategories for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on table public.subcategories to authenticated;
revoke all on table public.subcategories from anon;

-- Lançamentos e fixos: subcategoria opcional, sempre da categoria do lançamento.
-- Apagar a subcategoria só limpa a subcategoria (a categoria fica).
alter table public.entries add column if not exists subcategory_id bigint;
alter table public.recurring add column if not exists subcategory_id bigint;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'entries_subcategory_fkey') then
    alter table public.entries add constraint entries_subcategory_fkey
      foreign key (subcategory_id, category_id) references public.subcategories (id, category_id)
      on delete set null (subcategory_id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'recurring_subcategory_fkey') then
    alter table public.recurring add constraint recurring_subcategory_fkey
      foreign key (subcategory_id, category_id) references public.subcategories (id, category_id)
      on delete set null (subcategory_id);
  end if;
end;
$$;
create index if not exists entries_subcategory_idx on public.entries (subcategory_id);
create index if not exists recurring_subcategory_idx on public.recurring (subcategory_id);

-- ---------- formas de pagamento: tipo (ícone) e banco ----------

alter table public.payment_methods add column if not exists icon text not null default 'conta';
alter table public.payment_methods add column if not exists bank text;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'payment_methods_icon_check') then
    alter table public.payment_methods add constraint payment_methods_icon_check check (icon ~ '^[a-z_]{1,24}$');
  end if;
  if not exists (select 1 from pg_constraint where conname = 'payment_methods_bank_check') then
    alter table public.payment_methods add constraint payment_methods_bank_check check (bank is null or bank ~ '^[a-z0-9_]{1,24}$');
  end if;
end;
$$;

-- As que já existem: tipo e banco adivinhados pelo nome (dá para trocar em Configurações)
update public.payment_methods
   set icon = case
     when is_credit then 'credito'
     when name ~* '\mpix\M' then 'pix'
     when name ~* 'dinheiro|esp[eé]cie' then 'dinheiro'
     when name ~* '\m(vr|va|vale|ticket|alelo|sodexo|pluxee|caju|flash)\M' then 'vale'
     when name ~* 'd[eé]bito' then 'debito'
     when name ~* 'boleto' then 'boleto'
     when name ~* 'poupan[cç]a|caixinha' then 'poupanca'
     else 'conta'
   end
 where icon = 'conta';

