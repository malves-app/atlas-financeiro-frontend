-- Sugestões agora devolvem também a subcategoria usada da última vez
drop function if exists public.fm_suggestions();
create function public.fm_suggestions()
returns table (name text, category_id bigint, subcategory_id bigint, payment_method_id bigint, uses integer)
language sql
stable
security invoker
set search_path = ''
as $$
  with ranked as (
    select e.name, e.category_id, e.subcategory_id, e.payment_method_id,
           count(*) over (partition by lower(trim(e.name))) as uses,
           row_number() over (
             partition by lower(trim(e.name))
             order by (e.category_id is null), e.month desc, e.id desc
           ) as rn
      from public.entries e
     where e.kind = 'avulso'
  )
  select trim(r.name), r.category_id, r.subcategory_id, r.payment_method_id, r.uses::integer
    from ranked r
   where r.rn = 1
   order by r.uses desc, trim(r.name)
   limit 400;
$$;
revoke execute on function public.fm_suggestions() from public, anon;
grant execute on function public.fm_suggestions() to authenticated;

-- Preencher pelo histórico também copia a subcategoria
create or replace function public.fm_fill_categories(p_month text)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  n integer;
begin
  update public.entries e
     set category_id = h.category_id,
         subcategory_id = h.subcategory_id
    from (
      select distinct on (lower(trim(e2.name))) lower(trim(e2.name)) as key, e2.category_id, e2.subcategory_id
        from public.entries e2
       where e2.category_id is not null
       order by lower(trim(e2.name)), e2.month desc, e2.id desc
    ) h
   where e.month = p_month
     and e.category_id is null
     and lower(trim(e.name)) = h.key;
  get diagnostics n = row_count;
  return n;
end;
$$;
revoke execute on function public.fm_fill_categories(text) from public, anon;
grant execute on function public.fm_fill_categories(text) to authenticated;
